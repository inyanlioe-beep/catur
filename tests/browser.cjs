/* Optional integration checks: PLAYWRIGHT_MODULE can point to playwright-core. */
const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const server = spawn(process.execPath, [path.join(__dirname, '../server.js')], { env: { ...process.env, PORT: '3187' }, stdio: ['ignore', 'pipe', 'pipe'] });
let browser;
(async () => {
    await new Promise((resolve, reject) => { server.stdout.once('data', resolve); server.once('error', reject); server.once('exit', code => reject(new Error(`Server exited: ${code}`))); });
    browser = await chromium.launch({ headless: true, channel: 'chrome' });
    const context = await browser.newContext({ viewport: { width: 1440, height: 1100 } }), page = await context.newPage(), errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:3187');
    assert.equal(await page.locator('.square').count(), 64);
    assert.equal(await page.locator('.piece').count(), 32);
    const artifacts = path.join(__dirname, 'artifacts');
    fs.mkdirSync(artifacts, { recursive: true });
    await page.screenshot({ path: path.join(artifacts, 'desktop.png'), fullPage: true });
    const click = async (square) => page.locator(`[data-index="${(8 - Number(square[1])) * 8 + 'abcdefgh'.indexOf(square[0])}"]`).click();
    await page.selectOption('#gameMode', 'local');
    await click('e2');
    assert.equal(await page.locator('.valid-move').count(), 2);
    await click('e4');
    assert.equal(await page.locator('#moveCount').innerText(), '1');
    assert.equal(await page.locator('.latest').innerText(), 'e4');
    await click('d7');
    await click('d5');
    await click('e4');
    await click('d5');
    assert.equal(await page.locator('#capturedWhite').innerText(), '♟');
    await page.locator('#undoBtn').click();
    assert.equal(await page.locator('#capturedWhite').innerText(), '');
    assert.equal(await page.locator('#moveCount').innerText(), '2');
    await page.reload();
    assert.equal(await page.locator('#moveCount').innerText(), '2');
    await page.locator('#flipBtn').click();
    assert.equal(await page.locator('.square').first().getAttribute('data-index'), '63');
    const downloadPromise = page.waitForEvent('download');
    await page.locator('#exportBtn').click();
    const download = await downloadPromise;
    await download.saveAs(path.join(artifacts, 'game.pgn'));
    assert.match(fs.readFileSync(path.join(artifacts, 'game.pgn'), 'utf8'), /1\. e4 d5 \*/);
    await page.selectOption('#gameMode', 'computer');
    assert.equal(await page.locator('#newGameDialog').isVisible(), true);
    await page.locator('#cancelReset').click();
    assert.equal(await page.locator('#gameMode').inputValue(), 'local');
    await page.selectOption('#gameMode', 'computer');
    await page.locator('#confirmReset').click();
    await click('e2');
    await click('e4');
    await page.waitForFunction(() => history.length === 2 && !thinking);
    assert.equal(await page.locator('#moveCount').innerText(), '2');
    await page.locator('#undoBtn').click();
    assert.equal(await page.locator('#moveCount').innerText(), '0');
    // Cancel a scheduled AI move; it must never alter the reset position.
    await click('d2');
    await click('d4');
    await page.locator('#resetBtn').click();
    await page.locator('#confirmReset').click();
    await page.waitForTimeout(700);
    assert.equal(await page.locator('#moveCount').innerText(), '0');
    // Exercise both colors' special moves through actual UI interactions.
    await page.selectOption('#gameMode', 'local');
    async function position(board, turn = 'w', rights = '', ep = -1) {
        await page.evaluate(({ board, turn, rights, ep }) => {
            stopAI();
            state = { board: Array(64).fill(null), turn, rights, ep, half: 0, full: 1 };
            for (const [name, piece] of Object.entries(board))
                state.board[(8 - Number(name[1])) * 8 + 'abcdefgh'.indexOf(name[0])] = piece;
            history = [];
            positions = [Chess.key(state)];
            selected = null;
            flipped = false;
            render();
        }, { board, turn, rights, ep });
    }
    await position({ e1: 'K', h1: 'R', e8: 'k' }, 'w', 'K');
    await click('e1');
    await click('g1');
    assert.equal(await page.locator('[data-index="61"] .piece').innerText(), '♜');
    await page.locator('#undoBtn').click();
    assert.equal(await page.locator('[data-index="63"] .piece').innerText(), '♜');
    await position({ e1: 'K', a8: 'r', e8: 'k' }, 'b', 'q');
    await click('e8');
    await click('c8');
    assert.equal(await page.locator('[data-index="3"] .piece').innerText(), '♜');
    await page.locator('#undoBtn').click();
    assert.equal(await page.locator('[data-index="0"] .piece').innerText(), '♜');
    await position({ e1: 'K', e8: 'k', e4: 'p', d4: 'P' }, 'b', '', 43);
    await click('e4');
    await click('d3');
    assert.equal(await page.locator('[data-index="35"] .piece').count(), 0);
    await page.locator('#undoBtn').click();
    assert.equal(await page.locator('[data-index="35"] .piece').count(), 1);
    await position({ e1: 'K', e8: 'k', a7: 'P' });
    await click('a7');
    await click('a8');
    assert.equal(await page.locator('#promotionOptions button').count(), 4);
    await page.getByRole('button', { name: 'kuda', exact: true }).click();
    assert.equal(await page.locator('[data-index="0"] .piece').innerText(), '♞');
    await page.locator('#undoBtn').click();
    assert.equal(await page.locator('[data-index="8"] .piece').innerText(), '♟');
    await page.locator('#resetBtn').click();
    // Keyboard navigation and phone layout.
    await page.locator('#board [data-index="56"]').focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.evaluate(() => document.activeElement.dataset.index), '57');
    await page.keyboard.press('Enter');
    assert.equal(await page.locator('.selected').count(), 1);
    await page.keyboard.press('Escape');
    await page.setViewportSize({ width: 390, height: 844 });
    await page.screenshot({ path: path.join(artifacts, 'mobile.png'), fullPage: true });
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'No horizontal overflow');
    await page.selectOption('#gameMode', 'auto');
    await page.waitForFunction(() => history.length >= 4);
    await page.locator('#undoBtn').click();
    const paused = await page.locator('#moveCount').innerText();
    await page.waitForTimeout(700);
    assert.equal(await page.locator('#moveCount').innerText(), paused);
    // Corrupt storage recovers without breaking the page.
    await page.evaluate(() => localStorage.setItem('ruang-catur-v1', '{"history":[{"from":0,"to":63}]}'));
    await page.reload();
    assert.equal(await page.locator('#moveCount').innerText(), '0');
    assert.equal(await page.locator('.piece').count(), 32);
    assert.deepEqual(errors, []);
    console.log('Browser checks passed: local play, captures, AI, cancellation, undo, castling, en passant, promotion, persistence, PGN, keyboard, autoplay, and mobile layout.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { if (browser)
    await browser.close(); server.kill(); });
